"""Workstream 1, Task 1.3 -- response-format factorial.

Replaces the manuscript's 5-model/4-paraphrase robustness check with a full
factorial over response scale, item order, option order and elicitation mode
(see format_design.py for the design and the scale mappings).

Design (updates/03_experiments.md Task 1.3): 24 configurations x 19 models x 2 instruments x 5
trials = 4,560 administrations.

    export OPENROUTER_API_KEY=...
    python3 scoring/collect_format_factorial.py --trials 5 --cost-cap 70

Results land in data/format_factorial/ as
    {model}__{test}__{config_id}__trial{NN}.json
Each record stores the configuration, the RNG seed and the exact presentation
permutation, so any trial's prompt can be regenerated byte-for-byte from the
record alone -- which is what makes the item-order factor auditable rather
than merely asserted.

Analysis lives in analyze_w1.py.
"""

